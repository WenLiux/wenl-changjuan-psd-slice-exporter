def test_sorting_uses_top_left_then_original_index() -> None:
    resource = descriptor_resource(
        8,
        [
            descriptor_slice(
                slice_id=30,
                bounds=(50, 100, 100, 150),
                origin=b"userGenerated",
            ),
            descriptor_slice(
                slice_id=10,
                bounds=(0, 100, 50, 150),
                origin=b"userGenerated",
            ),
            descriptor_slice(
                slice_id=20,
                bounds=(0, 100, 50, 150),
                origin=b"userGenerated",
            ),
        ],
    )
    result = parse_slice_resource(resource, canvas_width=100, canvas_height=200)

    assert [item.slice_id for item in result.exportable_slices] == [10, 20, 30]
    assert "duplicate_bounds" in {issue.code for issue in result.issues}


@pytest.mark.parametrize(
    ("bounds", "issue_code"),
    [
        ((10, 20, 10, 100), "non_positive_size"),
        ((0, 0, 101, 100), "out_of_canvas"),
    ],
)
def test_invalid_bounds_are_excluded_with_structured_issue(
    bounds: tuple[int, int, int, int], issue_code: str
) -> None:
    resource = descriptor_resource(
        8,
        [
            descriptor_slice(
                slice_id=1,
                bounds=bounds,
                origin=b"userGenerated",
            )
        ],
    )
    result = parse_slice_resource(resource, canvas_width=100, canvas_height=100)

    assert not result.exportable_slices
    assert result.excluded_slices[0].slice_id == 1
    assert issue_code in {issue.code for issue in result.issues}
    assert result.has_errors


def test_malformed_and_unsupported_resources_raise_typed_errors() -> None:
    with pytest.raises(UnsupportedSliceVersionError):
        parse_slice_resource(
            SimpleNamespace(version=5, data={}),
            canvas_width=100,
            canvas_height=100,
        )

    with pytest.raises(MalformedSliceResourceError):
        parse_slice_resource(
            SimpleNamespace(version=8, data={}),
            canvas_width=100,
            canvas_height=100,
        )
